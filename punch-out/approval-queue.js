// Closes a gap flagged in certification review: human_approval_queue.json
// used to be a hand-authored artifact, copied after the fact from a run
// log — no code path ever wrote to it, so the "hand-off to a human" step
// existed only on paper. This module is that missing code path: it is
// called from workflow.js's finalizeRun() every time a run's final_status
// is PUNCH_OUT, and it appends a real entry, atomically, so the queue file
// always reflects exactly what the automated pipeline actually escalated.

const fs = require("fs");
const path = require("path");

const QUEUE_PATH = path.join(__dirname, "human_approval_queue.json");

function readQueue() {
  if (!fs.existsSync(QUEUE_PATH)) return [];
  const raw = fs.readFileSync(QUEUE_PATH, "utf8").trim();
  if (!raw) return [];
  return JSON.parse(raw);
}

function resourcesInvolved(run) {
  const a1 = run.steps.find((s) => s.step === "agent1_plan_analyzer");
  const findings = a1 && a1.parsed_output;
  if (!findings) return [];
  return [
    ...(findings.destructive_changes || []).map((c) => c.resource),
    ...(findings.security_exposure || []).map((c) => c.resource),
  ];
}

/**
 * Appends a real escalation entry for `run` (a finalized run object with
 * final_status === "PUNCH_OUT") to punch-out/human_approval_queue.json.
 * Writes atomically (write to a temp file, then rename) so a crash
 * mid-write can never leave the queue file truncated or corrupt.
 *
 * Deliberately does NOT dedupe by run_id: re-running the same run_id is a
 * genuinely distinct escalation event (a different execution at a
 * different time, possibly with different findings), so each is recorded
 * separately with its own `escalated_at` timestamp. In practice, running
 * the same fixed run_id repeatedly only happens during development/eval
 * iteration, not in normal operation — the queue file in this repo was
 * reset and regenerated by a single final pass through every scenario for
 * exactly that reason.
 */
function enqueueForHumanApproval(run) {
  const queue = readQueue();
  queue.push({
    run_id: run.run_id,
    scenario: run.scenario,
    environment: run.environment,
    escalated_at: run.timestamp,
    reason: run.final_status_reason,
    resources: resourcesInvolved(run),
    status: "AWAITING_HUMAN_APPROVAL",
    audit_log: `runs/${run.run_id}.json`,
  });

  const tmpPath = `${QUEUE_PATH}.tmp-${process.pid}`;
  fs.writeFileSync(tmpPath, JSON.stringify(queue, null, 2));
  fs.renameSync(tmpPath, QUEUE_PATH);
  return queue[queue.length - 1];
}

module.exports = { enqueueForHumanApproval, readQueue, QUEUE_PATH };
