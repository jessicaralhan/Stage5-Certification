// Report Writer Executor: Synthesizes findings into unified reports

require('dotenv').config({ override: true });

const fs = require('fs');
const path = require('path');
const { callClaude } = require('./anthropic-client');

function loadPrompt(name) {
  return fs.readFileSync(path.join(__dirname, `../prompts/${name}`), 'utf-8');
}

// Determine combined risk level from all workflows
function getCombinedRiskLevel(workflowFindings) {
  const severityOrder = { CRITICAL: 4, HIGH: 3, MEDIUM: 2, LOW: 1 };

  let maxSeverity = 0;
  Object.values(workflowFindings).forEach(findings => {
    if (findings && findings.risk_level) {
      maxSeverity = Math.max(maxSeverity, severityOrder[findings.risk_level] || 0);
    }
  });

  const severityMap = { 4: 'CRITICAL', 3: 'HIGH', 2: 'MEDIUM', 1: 'LOW', 0: 'LOW' };
  return severityMap[maxSeverity];
}

// Determine which workflows were triggered based on findings
function getTriggeredWorkflows(workflowFindings) {
  const triggered = [];

  if (workflowFindings.terraform && workflowFindings.terraform.workflow === 'terraform') {
    triggered.push('Terraform Safety Review (Infrastructure)');
  }
  if (workflowFindings.kubernetes && workflowFindings.kubernetes.workflow === 'kubernetes') {
    triggered.push('Kubernetes Security Review (Container Security)');
  }
  if (workflowFindings.iam && workflowFindings.iam.workflow === 'iam') {
    triggered.push('IAM Policy Audit (Access Control)');
  }

  return triggered;
}

// Build deterministic report structure with LLM-generated content
async function generateReport(workflowFindings) {
  try {
    // Determine triggered workflows and combined risk
    const triggeredWorkflows = getTriggeredWorkflows(workflowFindings);
    const combinedRiskLevel = getCombinedRiskLevel(workflowFindings);

    if (triggeredWorkflows.length === 0) {
      return '# Infrastructure & Security Review Report\n\nNo findings to report.\n';
    }

    // Load Report Writer prompt
    const reportWriterPrompt = loadPrompt('report-writer.md');

    // Prepare input for Report Writer
    const prompt = reportWriterPrompt
      .replace('{{triggered_workflows}}', triggeredWorkflows.join(', '))
      .replace('{{combined_risk_level}}', combinedRiskLevel)
      .replace('{{findings_json}}', JSON.stringify(workflowFindings, null, 2));

    // Call Report Writer agent
    process.stdout.write('  → Report Writer: Synthesizing findings into report...\n');

    const result = await callClaude({
      user: prompt,
      model: 'claude-haiku-5-5',
      maxTokens: 4000,
    });

    process.stdout.write('    ✓ Report generated\n');

    // Build deterministic structure: headings are determined by triggered workflows
    let finalReport = '# Infrastructure & Security Review Report\n\n';
    finalReport += `**Combined Risk Level**: ${combinedRiskLevel}\n\n`;

    // Add sections in deterministic order based on triggered workflows
    if (workflowFindings.terraform) {
      finalReport += '## Infrastructure (Terraform) Findings\n\n';
      finalReport += buildTerraformSection(workflowFindings.terraform);
    }

    if (workflowFindings.kubernetes) {
      finalReport += '## Container Security (Kubernetes) Findings\n\n';
      finalReport += buildKubernetesSection(workflowFindings.kubernetes);
    }

    if (workflowFindings.iam) {
      finalReport += '## Access Control (IAM) Findings\n\n';
      finalReport += buildIAMSection(workflowFindings.iam);
    }

    // Add LLM-generated synthesis and recommendations
    finalReport += '## Synthesis & Recommendations\n\n';
    finalReport += result.text + '\n\n';

    // Add audit note
    finalReport += '---\n\n*Report generated by Stage 5 Multi-Workflow Coordinator System*\n';

    return finalReport;
  } catch (err) {
    process.stderr.write(`Error generating report: ${err.message}\n`);
    return `# Error Generating Report\n\nFailed to synthesize findings: ${err.message}\n`;
  }
}

// Build Terraform section with deterministic content
function buildTerraformSection(findings) {
  let section = '';
  section += `**Risk Level**: ${findings.risk_level}\n\n`;

  if (findings.destructive_changes && findings.destructive_changes.length > 0) {
    section += '### Destructive Changes\n';
    findings.destructive_changes.forEach(change => {
      section += `- **${change.resource}** (${change.severity}): ${change.action}\n`;
      if (change.forcing_attribute) {
        section += `  - Attribute causing replacement: ${change.forcing_attribute}\n`;
      }
    });
    section += '\n';
  }

  if (findings.security_exposure && findings.security_exposure.length > 0) {
    section += '### Security Exposure\n';
    findings.security_exposure.forEach(exposure => {
      section += `- **${exposure.resource}** (${exposure.severity}): ${exposure.issue}\n`;
    });
    section += '\n';
  }

  if (findings.cost_notes && findings.cost_notes.length > 0) {
    section += '### Cost Impact\n';
    findings.cost_notes.forEach(note => {
      section += `- ${note}\n`;
    });
    section += '\n';
  }

  return section;
}

// Build Kubernetes section with deterministic content
function buildKubernetesSection(findings) {
  let section = '';
  section += `**Risk Level**: ${findings.risk_level}\n\n`;
  section += `${findings.summary || 'Kubernetes security analysis complete.'}\n\n`;

  if (findings.security_issues && findings.security_issues.length > 0) {
    section += '### Security Issues\n';
    findings.security_issues.forEach(issue => {
      section += `- **${issue.resource_name}** (${issue.resource_kind}, ${issue.severity})\n`;
      section += `  - Issue: ${issue.description}\n`;
    });
    section += '\n';
  }

  return section;
}

// Build IAM section with deterministic content
function buildIAMSection(findings) {
  let section = '';
  section += `**Risk Level**: ${findings.risk_level}\n\n`;
  section += `${findings.summary || 'IAM policy analysis complete.'}\n\n`;

  if (findings.access_issues && findings.access_issues.length > 0) {
    section += '### Access Issues\n';
    findings.access_issues.forEach(issue => {
      section += `- **${issue.type}** (${issue.severity}): ${issue.description}\n`;
    });
    section += '\n';
  }

  return section;
}

module.exports = { generateReport, getCombinedRiskLevel, getTriggeredWorkflows };
